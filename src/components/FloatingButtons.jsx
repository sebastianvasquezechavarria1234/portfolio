const FloatingButtons = () => {
  const [showScrollBtn, setShowScrollBtn] = useState(false)

  useEffect(() => {
    const handleScroll = () => {
      setShowScrollBtn(document.documentElement.scrollTop > 400)
    }
    window.addEventListener('scroll', handleScroll)
    return () => window.removeEventListener('scroll', handleScroll)
  }, [])

  const scrollToTop = (e) => {
    if (e) e.preventDefault()
    if (window.lenis) {
      window.lenis.scrollTo(0)
    } else {
      window.scrollTo({ top: 0, behavior: 'smooth' })
    }
  }

  return (
    <div className="fixed-button">
      <ul>
        <li onClick={scrollToTop} style={{ transform: showScrollBtn ? 'scale(1)' : 'scale(0)', cursor: 'pointer' }}>
          <a href="#" onClick={(e) => e.preventDefault()}>
            <ScrollTopSvg />
          </a>
        </li>
        <li style={{ transform: showScrollBtn ? 'scale(1)' : 'scale(0)' }}>
          <a href="https://wa.me/573015857417" target="_blank" rel="noopener noreferrer">
            <WhatsappSvg />
          </a>
        </li>
      </ul>
    </div>
  )
}

